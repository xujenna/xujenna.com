<p>
	I started contract-to-hire in February 2025 to cover the founding designer’s maternity leave, and joined full-time as their second product designer in July. Initially briefed to apply a new brand identity from Red Antler in addition to regular sprint work, I ultimately decided I couldn’t simply paint over the issues that taunted me: everything was competing for the user’s attention via duplicative surfaces, redundant entry points, and floating action buttons everywhere; Mem's most differentiating and overlapping AI features were scattered across three disconnected surfaces that users weren’t reaching for; visual hierarchy—especially typographic, critical for a notes app—was all but nonexistent. 
</p>
<p>
	As with most freelance gigs and FT jobs across my career, I was soon leading a comprehensive redesign: a six-month effort to overhaul the product's visual language, information architecture, and interaction model, optimizing the overall experience to better align with the brand promise of catalyzing the potential of every thought. My work would culminate in October 2025 as the Mem 2.0 relaunch.
</p>
<p>
<b>Goals:</b> Relaunch Mem with a new brand and a dramatically optimized product experience. Consolidate fragmented AI surfaces and interaction patterns, simplify the IA, eliminate redundancy, add long-requested features like dark mode and multitasking, improve discoverability of differentiating features, and ship it all as a single coordinated moment.
