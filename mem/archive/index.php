//Visual system
//Throughout the foregoing explorations, I was simultaneously honing in on a new visual language with every mock—based on the brand direction from Red Antler, the idea that Mem is an app that users work, play, and live in, as well as the founder’s affinity for organic modern interior design.
//[organic modern]
//I built the full visual system from scratch: color ramps enabling the warm canvas-and-latte palette that replaced Mem's cold and very purple scheme, as well as a unique dark mode that was also based on the brand palette, requiring its own careful tweaking (not a simple inversion); and type styles. The returning designer collaborated with engineers to lead the formalization of the design system, including the implementation of a component library and semantic variables.
