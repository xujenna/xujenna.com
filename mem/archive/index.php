//Restructured sidebar & IA. The old sidebar siloed content into Library/Notes/Collections/Templates with flat Pinned and Recents lists below. The new sidebar unifies pinned notes and collections together (reflecting how people actually prioritize), with collapsible sections and collection tags visible inline on every note in list view—organization visible at a glance.
