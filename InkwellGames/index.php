<p>As the first design consultant at Inkwell Games, a Carina Fund-incubated startup, I designed the complete user experience for a web-based daily puzzle platform centered on mathematical logic games. The platform's thesis was that daily math puzzles could reach a mass audience if they felt approachable rather than academic, while positioning themselves as a premium, ad-free alternative to NYT Games. I worked alongside the founder and an engineer to help launch the company's public beta.</p>
<p>
My work spanned end-to-end user flows, wireframes, and ultimately hifi interfaces for the landing page and their first puzzle game, as well as a reusable component library designed to scale across puzzle formats. I helped with a competitive analysis of the daily puzzle landscape to inform interaction design patterns, integrated a new agency-produced brand identity into the design system, and advocated for a more accessible mobile web experience—larger tap targets and type, simpler architecture and layout to reduce scrolling—to better serve the platform's older target audience.</p>
